import {test,expect} from '@playwright/test';
const save=async(page,name)=>{
  if(process.env.CAPTURE_SCREENSHOTS) await page.screenshot({path:'docs/screenshots/'+name+'.png',fullPage:true});
};
test('overview lets users isolate segments and recompute cluster counts',async({page})=>{
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Mall customer segments'})).toBeVisible();
  await expect(page.locator('#plot circle')).toHaveCount(200);
  await save(page,'01-overview');
  const segment=page.getByRole('button',{name:'Segment 02',exact:true});
  await segment.click();
  await expect(segment).toHaveAttribute('aria-pressed','true');
  expect(await page.locator('#plot circle[opacity="0.1"]').count()).toBeGreaterThan(0);
  await save(page,'02-segment-focus');
  await page.getByLabel('Clusters',{exact:true}).selectOption('7');
  await expect(page.locator('.bar-label')).toHaveCount(7);
  await expect(page.getByRole('button',{name:'All',exact:true})).toHaveAttribute('aria-pressed','true');
  await save(page,'03-seven-clusters');
  await page.getByRole('button',{name:'Explore segment profiles'}).click();
  await expect(page.locator('.profile')).toHaveCount(7);
  expect(errors).toEqual([]);
});
test('profiles and assignment use the current model; invalid inputs are rejected',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Segments',exact:true}).click();
  await expect(page.locator('.profile')).toHaveCount(5);
  await save(page,'04-segment-profiles');
  await page.getByRole('button',{name:'Overview'}).click();
  await page.getByLabel('Clusters',{exact:true}).selectOption('7');
  await page.getByRole('button',{name:'Predict'}).click();
  await page.getByRole('spinbutton',{name:'Spending score (1–100)'}).fill('101');
  await page.getByRole('button',{name:'Assign segment'}).click();
  await expect(page.getByRole('heading',{name:'Assignment result'})).toBeVisible();
  await page.getByRole('spinbutton',{name:'Spending score (1–100)'}).fill('78');
  await page.getByRole('button',{name:'Assign segment'}).click();
  await expect(page.locator('#result h2')).toHaveText(/Segment 0[1-7]/);
  await expect(page.locator('#result')).toContainText('7 clusters');
  await save(page,'05-customer-assignment');
});
test('mobile workspace fits the viewport and supports keyboard navigation',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await save(page,'06-mobile-overview');
  const tab=page.getByRole('button',{name:'Predict'});
  await tab.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading',{name:'Assign a customer'})).toBeFocused();
  await page.getByRole('button',{name:'Assign segment'}).click();
  await expect(page.locator('#result h2')).toHaveText(/Segment 0[1-5]/);
  await save(page,'07-mobile-assignment');
});
test('field guide explains ranges and returns focus; infographic reflects current model',async({page})=>{
  await page.goto('/');
  const trigger=page.getByRole('button',{name:'Help: Customer landscape',exact:true});
  await trigger.click();
  const dialog=page.getByRole('dialog');
  await expect(dialog).toContainText('$15k–$137k');
  await save(page,'08-chart-field-guide');
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await page.getByLabel('Clusters',{exact:true}).selectOption('7');
  await expect(page.locator('.flow')).toContainText('7 groups');
  await page.locator('.flow').screenshot({path:process.env.CAPTURE_SCREENSHOTS?'docs/screenshots/09-model-infographic.png':undefined});
  await page.getByRole('button',{name:'Predict'}).click();
  await page.getByRole('button',{name:'Help: Annual income ($k)',exact:true}).click();
  await expect(dialog).toContainText('$88,000');
  await save(page,'10-prediction-field-guide');
  await dialog.getByRole('button',{name:'Got it'}).click();
  await expect(dialog).not.toBeVisible();
});
